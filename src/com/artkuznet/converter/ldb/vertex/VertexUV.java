package com.artkuznet.converter.ldb.vertex;

public class VertexUV {

    private float u;
    private float v;

    public VertexUV(float u, float v) {
        this.u = u;
        this.v = v;
    }

    public float getU() {
        return u;
    }

    public float getV() {
        return v;
    }
}
